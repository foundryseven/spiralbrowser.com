export const defaultLocale = 'en';
export const locales = ['en', 'de', 'fr', 'ja'] as const;
export type Locale = (typeof locales)[number];

export function getLocaleFromUrl(url: URL): Locale {
  const [, lang] = url.pathname.split('/');
  if (lang && (locales as readonly string[]).includes(lang)) {
    return lang as Locale;
  }
  return defaultLocale;
}

export function t(locale: Locale, key: string): string {
  const localised = (ui[locale] as Record<string, string>)[key];
  if (localised !== undefined) return localised;
  return (ui.en as Record<string, string>)[key] ?? key;
}

export function pickLocale<T>(locale: Locale, items: Record<Locale, T>): T {
  return items[locale] ?? items[defaultLocale];
}
